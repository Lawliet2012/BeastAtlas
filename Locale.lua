ns.L = setmetatable(ns.IS_RU and ru or en, { __index = en })

-- Primary name in the client language, secondary in the other one.
function ns.Names(obj)
    if ns.IS_RU then return obj.ru or obj.en, obj.en end
    return obj.en, obj.ru
end

-- "Primary" or "Primary |cff888888/ Secondary|r" depending on settings.
function ns.DisplayName(obj, inline)
    local a, b = ns.Names(obj)
    local mode = BeastAtlasDB and BeastAtlasDB.names or "both"
    if mode ~= "both" or not b or b == a then return a end
    if inline then return a .. " |cff8a8a8a/ " .. b .. "|r" end
    return a, b
end
